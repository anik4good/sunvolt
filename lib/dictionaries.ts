export const dictionaries: Record<Lang, Dictionary> = { bn, en };

/** Language-aware number: 12 → ১২ in Bengali, 12 in English. */
export function num(value: number | string, lang: Lang): string {
  return lang === "bn" ? toBn(value) : String(value);
}

/** Replace {placeholders} in a dictionary template. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    key in vars ? String(vars[key]) : `{${key}}`,
  );
}
